import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import manifest from "@/app/manifest";

const pub = (p: string) => join(process.cwd(), "public", p);

describe("PWA assets", () => {
  const m = manifest();

  it("every icon in the manifest exists on disk", () => {
    for (const icon of m.icons ?? []) expect(existsSync(pub(icon.src)), icon.src).toBe(true);
  });

  it("has separate maskable icons at 192 and 512, not a reused 'any' file", () => {
    const maskable = (m.icons ?? []).filter((i) => i.purpose === "maskable");
    const any = (m.icons ?? []).filter((i) => i.purpose === "any");
    expect(maskable.map((i) => i.sizes).sort()).toEqual(["192x192", "512x512"]);
    for (const i of maskable) expect(any.map((a) => a.src)).not.toContain(i.src);
  });

  it("shortcuts point at real pages", () => {
    for (const s of m.shortcuts ?? []) expect(s.url).toMatch(/^\/(upload|dashboard)$/);
  });

  it("the service worker only precaches files that exist", () => {
    const sw = readFileSync(pub("sw.js"), "utf8");
    const list = sw.match(/const STATIC = \[([\s\S]*?)\];/)?.[1] ?? "";
    const files = [...list.matchAll(/"([^"]+)"/g)].map((x) => x[1]);
    expect(files.length).toBeGreaterThan(3);
    for (const f of files) {
      if (f === "/manifest.webmanifest") continue; // generated by app/manifest.ts
      expect(existsSync(pub(f)), f).toBe(true);
    }
  });

  it("the offline page is precached and the service worker version was bumped with it", () => {
    const sw = readFileSync(pub("sw.js"), "utf8");
    expect(sw).toContain('OFFLINE_URL = "/offline"');
    expect(sw).not.toContain("cma-static-v1");
  });
});
